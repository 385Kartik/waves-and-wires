export function getProductBySlug(slug: string): Product | undefined {
  return products.find(p => p.slug === slug);
}

export function getProductsByCategory(categoryIdOrSlug: string): Product[] {
  const target = (categoryIdOrSlug || '').toLowerCase();
  return products.filter(p => p.category_id === categoryIdOrSlug || (p.category_name || '').toLowerCase().includes(target));
}

export function getFeaturedProducts(): Product[] {
  return products.filter(p => Boolean(p.is_featured));
}

export function searchProducts(query: string): Product[] {
  const q = (query || '').toLowerCase();
  return products.filter(p =>
    (p.name || '').toLowerCase().includes(q) ||
    (p.description || '').toLowerCase().includes(q) ||
    (p.category_name || '').toLowerCase().includes(q)
  );
}
